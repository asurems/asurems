<?php
/**
 * ASU-REMS authenticated avatar helper.
 * Save this file as: includes/profile_avatar.php
 * Uses the same users.profile_photo column and uploads/profile_pictures folder
 * as the Create Account profile-picture feature.
 */

if (!function_exists('remsProfilePictureRelativePath')) {
    function remsProfilePictureRelativePath($pdo, int $userId): string
    {
        static $cache = [];
        if ($userId < 1) return '';
        if (array_key_exists($userId, $cache)) return $cache[$userId];

        $cache[$userId] = '';
        try {
            $stmt = $pdo->prepare('SELECT profile_photo FROM users WHERE user_id = ? LIMIT 1');
            $stmt->execute([$userId]);
            $path = (string)($stmt->fetchColumn() ?: '');

            // Only paths generated by the account-photo uploader are trusted.
            if (preg_match('~\Auploads/profile_pictures/[a-f0-9]{32}\.(?:jpg|png|webp)\z~D', $path)
                && is_file(dirname(__DIR__) . '/' . $path)) {
                $cache[$userId] = $path;
            }
        } catch (Throwable $exception) {
            // Prior installations without the migration keep the initials avatar.
            error_log('ASU-REMS profile picture lookup failed: ' . $exception->getMessage());
        }
        return $cache[$userId];
    }
}

if (!function_exists('remsProfileAvatarHtml')) {
    /** Safe, clickable avatar for topbars. Clicking opens the full photo and change-photo form. */
    function remsProfileAvatarHtml($pdo, array $user, string $initials, string $className = 'user-avatar'): string
    {
        $userId = (int)($user['user_id'] ?? 0);
        $relative = remsProfilePictureRelativePath($pdo, $userId);
        $safe = static fn(string $s): string => htmlspecialchars($s, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
        $initials = trim($initials) !== '' ? strtoupper(trim($initials)) : 'U';
        $initials = substr($initials, 0, 3);
        $className = trim((string)(preg_replace('/[^a-zA-Z0-9_\-\s]/', '', $className) ?: 'user-avatar'));

        $returnUrl = (string)($_SERVER['REQUEST_URI'] ?? '');
        $profileUrl = BASE_URL . '/profile.php';
        if ($returnUrl !== '' && strlen($returnUrl) <= 1500) {
            $path = parse_url($returnUrl, PHP_URL_PATH);
            if (is_string($path) && str_starts_with($path, rtrim(BASE_URL, '/') . '/')
                && !str_contains($returnUrl, "\r") && !str_contains($returnUrl, "\n")) {
                $profileUrl .= '?return=' . rawurlencode($returnUrl);
            }
        }

        $content = '';
        if ($relative !== '') {
            $src = BASE_URL . '/' . $relative;
            $content = '<img src="' . $safe($src) . '" alt="" class="rems-profile-avatar-img" '
                . 'style="width:100%;height:100%;display:block;object-fit:cover;border-radius:50%;" '
                . 'onerror="this.style.display=\'none\';this.nextElementSibling.style.display=\'inline-flex\';">'
                . '<span class="rems-profile-avatar-fallback" style="display:none;align-items:center;justify-content:center;width:100%;height:100%;">' . $safe($initials) . '</span>';
        } else {
            $content = '<span class="rems-profile-avatar-fallback" style="display:inline-flex;align-items:center;justify-content:center;width:100%;height:100%;">' . $safe($initials) . '</span>';
        }

        return '<a href="' . $safe($profileUrl) . '" class="' . $safe($className) . ' rems-profile-avatar-link" '
            . 'title="View or change profile picture" aria-label="View or change your profile picture" '
            . 'style="display:inline-flex;align-items:center;justify-content:center;overflow:hidden;flex-shrink:0;padding:0;text-decoration:none;cursor:pointer;">'
            . $content . '</a>';
    }
}
